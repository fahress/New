// Writes the agent gateway as one file, for pasting into the Supabase dashboard
// (Edge Functions → Deploy a new function → Via editor) when the Supabase CLI isn't available.
// Usage: node scripts/gateway-single-file.mjs [output.ts]   (prints to stdout without an argument)
import { readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../supabase/functions/agent-gateway/', import.meta.url);
const lib = readFileSync(new URL('lib.ts', dir), 'utf8');
let index = readFileSync(new URL('index.ts', dir), 'utf8');
index = index.replace(/^import \{[\s\S]*?\} from '\.\/lib\.ts';\n/m, ''); // the helpers are inlined below
index = index.replace(/^type Json = Record<string, unknown>;\n/m, ''); // already declared by the helpers
if (/from '\.\/lib\.ts'/.test(index)) throw new Error('index.ts still imports lib.ts');
const out = `// Fahress agent gateway — single-file version of supabase/functions/agent-gateway (index.ts + lib.ts).
// Generated by scripts/gateway-single-file.mjs. Edit the two source files, not this one.

${lib}
/* ============================== handler (index.ts) ============================== */
${index}`;
const target = process.argv[2];
if (target) writeFileSync(target, out); else process.stdout.write(out);
